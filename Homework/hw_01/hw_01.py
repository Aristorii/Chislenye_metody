# БЛОК 1. АБСОЛЮТНАЯ И ОТНОСИТЕЛЬНАЯ ПОГРЕШНОСТЬ (Задачи 1-5)

print("Задача 1. Ручной счёт")
pairs = [
    (3.14, math.pi, "pi"),
    (2.718, math.e, "e"),
    (9.8, 9.81, "g"),
    (0.333, 1/3, "1/3")
]

for x, x_star, name in pairs:
    dx = abs(x - x_star)
    delta_x = (dx / x_star) * 100
    print(f"{name}: dx = {dx:.5f}, delta = {delta_x:.4f}%")

# Вывод: 
# По качеству приближения (относительной погрешности) пары располагаются так: 
# 2 (e, лучшая) < 1 (pi) < 4 (1/3) < 3 (g, худшая).
# Порядок по dx и delta совпадает, так как значения не отличаются на порядки. 
# Если бы сравнивали мост (1000 м) и болт (10 мм), порядок бы не совпал, 
# так как абсолютная погрешность не учитывает масштаб.

print("Задача 2. Сравнение несопоставимых величин")
# Мост: x = 1247, точное 1250. dx = 3, delta = 3/1250 = 0.24%
# Болт: x = 9.7, точное 10.0. dx = 0.3, delta = 0.3/10.0 = 3.0%
# Вывод: Инженер ошибся "сильнее" с болтом (относительная погрешность 3% > 0.24%).
# Ответ зависит от выбора: по абсолютной ошибке промах с мостом больше (3 м > 0.3 мм), 
# но по относительной — с болтом.

def relative_error(approx, exact):
    if exact == 0:
        return float('inf')  # Защита от деления на ноль
    return abs(approx - exact) / abs(exact)

print("\n--- Задача 3. Функция relative_error ---")
for x, x_star, name in pairs:
    print(f"{name}: {relative_error(x, x_star):.6f}")

print("Задача 4. Обратная задача")
# x = 47.3, delta <= 0.1%. Диапазон: x +/- x*delta
x = 47.3
delta = 0.001
d = x * delta
print(f"x* принадлежит интервалу [{x - d:.4f}, {x + d:.4f}]")
# Ответ: [47.25, 47.35] (с учетом точности до 3 значащих цифр)

print("Задача 5. Порог по абсолютной и относительной ошибке")
# Датчик A: dx = 0.3. Датчик B: delta = 0.5%.
# Условие точности B: T * 0.005 <= 0.3 => T <= 60.
# Вывод: Датчик B точнее при температурах <= 60 C. 
# При малых T (например, 1 C) B дает крошечную абсолютную ошибку (0.005), 
# при больших (1000 C) — огромную (5 градусов), и A будет лучше.


