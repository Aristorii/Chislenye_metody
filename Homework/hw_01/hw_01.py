# БЛОК 3. НАКОПЛЕНИЕ ОШИБКИ И FLOAT-ЭКСПЕРИМЕНТЫ (Задачи 10-15)

print("\n--- Задача 10. Классика 0.1 + 0.2 ---")
print("0.1 + 0.2 == 0.3:", 0.1 + 0.2 == 0.3) # False
print("math.isclose:", math.isclose(0.1 + 0.2, 0.3)) # True

# Вывод: Дробь 0.1 в двоичной системе бесконечна (как 1/3 в десятичной). 
# Компьютер ее обрезает, возникает крошечная ошибка. Для сравнения float нужен isclose.

print("Задача 11. Катастрофическая потеря точности")
a, b = 1.0, 1e-15
diff = a - b
print(f"a - b = {diff} (вместо 0.999999999999999)")

# Вывод: При вычитании почти равных чисел старшие разряды сокращаются, остается мусор.
# В квадратичной формуле нужно использовать эквивалентную формулу x = 2c / (-b - sqrt(...)), 
# чтобы избежать вычитания почти равных чисел.

print("Задача 12. Накопление в цикле")
arr = [0.1] * 1_000_000
exact = 1e5
s_loop = 0.0
for x in arr:
    s_loop += x
print(f"Цикл: ошибка {abs(s_loop - exact):.2e}")
print(f"sum(): ошибка {abs(sum(arr) - exact):.2e}")
print(f"fsum(): ошибка {abs(math.fsum(arr) - exact):.2e}")

# Вывод: math.fsum самый точный, так как использует алгоритм компенсации потерь (Shewchuk).

print("Задача 13. Суммирование в правильном порядке")

# Вывод: Лучше суммировать от меньших к большим, чтобы накопить маленькие значения.
# Но если разница в порядках огромна, они все равно потеряются. Лучший метод — fsum.

